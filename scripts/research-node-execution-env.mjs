// Research only: overlay the skill host in memory and measure the full bundle.
// Run from the repo root: node scripts/research-node-execution-env.mjs
// No source, dependency, or build artifact is written; esbuild is stopped below.
import esbuild from "esbuild";
import { builtinModules } from "node:module";
import { readFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const userSkillsPath = path.join(root, "src/skills/userSkills.ts");
const original = await readFile(userSkillsPath, "utf8");
const boundary = `
declare const require: (id: string) => any;
function probe(): { home: string } | undefined {
  try {
    const fs = require("node:fs/promises");
    const os = require("node:os");
    const path = require("node:path");
    if (!fs || !["lstat", "readdir", "readFile", "realpath"].every(key => typeof fs[key] === "function") ||
        typeof os?.homedir !== "function" ||
        !path || !["join", "resolve", "basename", "isAbsolute"].every(key => typeof path[key] === "function")) return;
    return { home: os.homedir() };
  } catch { return; }
}
export function homeSkillsSupported() { return probe() !== undefined; }
export async function createHomeSkillEnv() {
  const host = probe();
  if (!host) return;
  const { create } = await import("./nodeSkillEnv");
  return create(host.home);
}
`;
const bridge = `
import { NodeExecutionEnv } from "@earendil-works/pi-agent-core/node";
import { err, ExecutionError, FileError } from "@earendil-works/pi-agent-core";
class SkillEnv extends NodeExecutionEnv {
  async exec() { return err(new ExecutionError("shell_unavailable", "The user-skill environment has no shell")); }
  async createTempDir() { return err(new FileError("not_supported", "Temporary files are not used by user skills", this.cwd)); }
  async createTempFile() { return err(new FileError("not_supported", "Temporary files are not used by user skills", this.cwd)); }
}
export function create(cwd: string) { return new SkillEnv({ cwd }); }
`;

function replaceOnce(source, before, after) {
  if (!source.includes(before) || source.indexOf(before) !== source.lastIndexOf(before)) {
    throw new Error(`Source changed; review the research overlay: ${before}`);
  }
  return source.replace(before, after);
}

let patched = replaceOnce(original, 'import { NodeHomeEnv } from "./nodeHomeEnv";',
  'import { createHomeSkillEnv, homeSkillsSupported } from "./homeSkillEnvironment";');
patched = replaceOnce(patched, "env: ExecutionEnv = new NodeHomeEnv()", "env?: ExecutionEnv");
patched = replaceOnce(patched, "if (env instanceof NodeHomeEnv && !env.available) {",
  "if (env) return loadUserSkillsFromEnv(env, customDir);\n\tenv = await createHomeSkillEnv();\n\tif (!env) {");
patched = replaceOnce(patched, "\treturn loadUserSkillsFromEnv(env, customDir);",
  "\ttry { return await loadUserSkillsFromEnv(env, customDir); } finally { await env.cleanup(); }");
patched = replaceOnce(patched, "return new NodeHomeEnv().available;", "return homeSkillsSupported();");

// Mirrors esbuild.config.mjs production options. A baseline size match verifies
// these settings against the real build; recheck if the production config moves.
const options = {
  absWorkingDir: root,
  banner: { js: "/*\nTHIS IS A GENERATED/BUNDLED FILE BY ESBUILD\nif you want to view the source, please visit the github repository of this plugin\n*/\n" },
  entryPoints: ["src/main.ts"],
  alias: {
    openai: path.join(root, "src/net/shims/openaiSdk.ts"),
    "@anthropic-ai/sdk": path.join(root, "src/net/shims/anthropicSdk.ts"),
  },
  loader: { ".png": "dataurl", ".md": "text" },
  external: ["obsidian", "electron", "@codemirror/autocomplete", "@codemirror/collab", "@codemirror/commands",
    "@codemirror/language", "@codemirror/lint", "@codemirror/search", "@codemirror/state", "@codemirror/view",
    "@lezer/common", "@lezer/highlight", "@lezer/lr", ...builtinModules],
  bundle: true, format: "cjs", target: "es2018", treeShaking: true,
  minify: true, sourcemap: false, metafile: true, write: false, outfile: "main.js", logLevel: "silent",
};

const measurements = [];
try {
  for (const mode of ["baseline", "bridge", "direct"]) {
    const result = await esbuild.build({
      ...options,
      external: [...options.external, ...(mode === "baseline" ? [] : ["node:*"])],
      plugins: mode === "baseline" ? [] : [{ name: "research-overlay", setup(build) {
        build.onLoad({ filter: /src\/skills\/userSkills\.ts$/ }, () => ({ contents: patched, loader: "ts", resolveDir: path.dirname(userSkillsPath) }));
        build.onResolve({ filter: /^\.\/(homeSkillEnvironment|nodeSkillEnv)$/ }, args => ({ path: args.path.slice(2), namespace: "probe" }));
        build.onLoad({ filter: /.*/, namespace: "probe" }, args => ({
          contents: args.path === "nodeSkillEnv" ? bridge : mode === "bridge" ? boundary :
            replaceOnce(boundary,
              'const { create } = await import("./nodeSkillEnv");\n  return create(host.home);',
              'const { NodeExecutionEnv } = await import("@earendil-works/pi-agent-core/node");\n  return new NodeExecutionEnv({ cwd: host.home });'),
          loader: "ts", resolveDir: path.dirname(userSkillsPath),
        }));
      }}],
    });
    const output = result.metafile.outputs["main.js"];
    const bytes = result.outputFiles[0].contents.byteLength;
    measurements.push({ mode, bytes, delta: bytes - (measurements[0]?.bytes ?? bytes),
      providerInputs: Object.entries(output.inputs)
        .filter(([file, info]) => file.includes("pi-ai/dist/providers/") && info.bytesInOutput > 0)
        .map(([file, info]) => ({ file, bytes: info.bytesInOutput })),
    });
  }
  console.log(JSON.stringify(measurements, null, 2));
} finally {
  esbuild.stop();
}
